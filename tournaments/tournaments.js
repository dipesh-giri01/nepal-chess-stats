const PRIMARY = '#766AF5';
const SECOND = '#DB2777';
const MUTED = '#656C86';
const HAIR = '#E6EAF4';
const NEUTRAL = '#CED3E3';
const COLORS = { Standard: PRIMARY, Rapid: SECOND, Blitz: NEUTRAL };
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const $ = (id) => document.getElementById(id);
const segVal = (id) => $(id).querySelector('[aria-pressed="true"]').dataset.v;
function onSeg(id, fn) {
  $(id).addEventListener('click', (e) => {
    const b = e.target.closest('button');
    if (!b) return;
    $(id).querySelectorAll('button').forEach((x) => x.setAttribute('aria-pressed', x === b));
    fn();
  });
}

Chart.register(ChartDataLabels);
Chart.defaults.font.family = "'IBM Plex Sans', sans-serif";
Chart.defaults.color = MUTED;
Chart.defaults.plugins.legend.display = false;
Chart.defaults.datasets.bar.categoryPercentage = 0.7;
Chart.defaults.datasets.bar.barPercentage = 0.8;
if (matchMedia('(prefers-reduced-motion: reduce)').matches) Chart.defaults.animation = false;

const io = new IntersectionObserver((es) => es.forEach((e) => e.isIntersecting && (e.target.classList.add('is-in'), io.unobserve(e.target))), { threshold: 0.12 });
document.querySelectorAll('.reveal').forEach((el) => io.observe(el));

// data.json is generated by build_data.py
fetch('data.json')
  .then((r) => {
    if (!r.ok) throw new Error(r.status);
    return r.json();
  })
  .then(start)
  .catch((err) => {
    $('etitle').textContent = 'Could not load data.json';
    $('empty').hidden = false;
    $('empty').textContent = `Error: ${err.message}. Open this page through a web server (GitHub Pages, or "python3 -m http.server" in the repo root), not straight from disk.`;
  });

function start({ events: ALL }) {
  ALL.forEach((e) => { e.year = +e.start.slice(0, 4); e.month = +e.start.slice(5, 7) - 1; });
  const first = Math.min(...ALL.map((e) => e.year));
  const last = Math.max(...ALL.map((e) => e.year));
  const years = Array.from({ length: last - first + 1 }, (_, i) => first + i);
  const FORMATS = Object.keys(COLORS);

  const fide = (id) => 'https://ratings.fide.com/tournament_information.phtml?event=' + encodeURIComponent(id);
  const esc = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
  const fmtN = (n) => n.toLocaleString();
  const inFmt = () => { const f = segVal('fmt'); return ALL.filter((e) => !f || e.fmt === f); };
  const grid = { color: HAIR, drawTicks: false };
  const labelOpts = { anchor: 'end', align: 'end', color: MUTED, font: { size: 10, weight: '500' } };

  // ---- charts ----
  const yearChart = new Chart($('yearChart'), {
    type: 'bar',
    data: { labels: years, datasets: FORMATS.map((f) => ({ label: f, backgroundColor: COLORS[f], data: [] })) },
    options: {
      maintainAspectRatio: false,
      layout: { padding: { top: 20 } },
      scales: {
        x: { stacked: true, grid: { display: false } },
        y: { stacked: true, beginAtZero: true, grid, border: { display: false }, ticks: { padding: 8, precision: 0 } },
      },
      onClick: (_, els) => els.length && pickYear(years[els[0].index]),
      plugins: { datalabels: { display: false } },
    },
  });

  const monthChart = new Chart($('monthChart'), {
    type: 'bar',
    data: { labels: MONTHS, datasets: [{ label: 'Tournaments', backgroundColor: PRIMARY, data: [] }] },
    options: {
      maintainAspectRatio: false,
      layout: { padding: { top: 20 } },
      scales: {
        x: { grid: { display: false } },
        y: { beginAtZero: true, grid, border: { display: false }, ticks: { padding: 8, precision: 0 } },
      },
      plugins: { datalabels: { display: (c) => !!c.dataset.data[c.dataIndex], ...labelOpts } },
    },
  });

  function renderCharts() {
    const f = segVal('fmt'), list = inFmt();
    FORMATS.forEach((fm, i) => {
      yearChart.data.datasets[i].data = years.map((y) => list.filter((e) => e.year === y && e.fmt === fm).length);
      yearChart.data.datasets[i].hidden = !!f && f !== fm;
    });
    yearChart.update();
    document.querySelectorAll('.legend-item[data-fmt]').forEach((el) => (el.hidden = !!f && el.dataset.fmt !== f));

    const perYear = years.map((y) => list.filter((e) => e.year === y).length);
    const peak = perYear.indexOf(Math.max(...perYear));
    const what = f ? f.toLowerCase() + ' tournaments' : 'tournaments';

    const perMonth = MONTHS.map((_, m) => list.filter((e) => e.month === m).length);
    monthChart.data.datasets[0].data = perMonth;
    monthChart.data.datasets[0].backgroundColor = f ? COLORS[f] : PRIMARY;
    monthChart.update();

    const topM = perMonth.indexOf(Math.max(...perMonth));
    $('year-insight').textContent = list.length
      ? `${years[peak]} is the busiest year with ${perYear[peak]} ${what}. ${last} is the latest year in the archive and may be incomplete.`
      : '';
    $('month-insight').textContent = list.length
      ? `${MONTHS[topM]} has the most starts: ${perMonth[topM]} of ${fmtN(list.length)} ${what}.`
      : '';

    const cur = perYear[years.length - 1];
    $('scoreboard').innerHTML = [
      [fmtN(list.length), `FIDE rated ${what} since ${first}`],
      [cur, `in ${last}, so far`],
      [years[peak], `busiest year (${perYear[peak]})`],
      f ? [Math.round((100 * list.length) / ALL.length) + '%', 'of all rated tournaments'] :
        [Math.round((100 * list.filter((e) => e.fmt !== 'Standard').length) / list.length) + '%', 'rapid or blitz'],
    ].map(([n, l]) => `<div class="stat"><div class="stat-num">${n}</div><div class="stat-label">${l}</div></div>`).join('');
  }

  // ---- tournament list ----
  $('year').innerHTML += [...years].reverse().map((y) => `<option value="${y}">${y}</option>`).join('');
  const STEP = 100; // rows per 'Show more' click
  let shown = STEP;
  const filtered = () => {
    const q = $('q').value.trim().toLowerCase(), y = $('year').value ? +$('year').value : null, cap = $('cap').value;
    return inFmt().filter((e) => (y === null || e.year === y) &&
      (!cap || (e.cap !== null) === (cap === '1')) &&
      (!q || `${e.name} ${e.city} ${e.org} ${e.arb}`.toLowerCase().includes(q)));
  };
  function renderEvents() {
    const y = $('year').value ? +$('year').value : null, list = filtered();
    $('etitle').textContent = (y === null ? 'All tournaments' : `Tournaments in ${y}`) + ` (${fmtN(list.length)})`;
    $('events').tBodies[0].innerHTML = list.slice(0, shown).map((e) =>
      `<tr><td class="nw">${e.start}</td><td><a href="${fide(e.id)}" target="_blank" rel="noopener">${esc(e.name)}</a></td>` +
      `<td>${esc(e.city)}</td><td>${e.fmt}</td><td>${e.cap ? 'Below ' + e.cap : ''}</td><td class="num">${e.n ?? ''}</td><td class="org">${esc(e.org)}</td><td class="arb nw">${esc(e.arb)}</td></tr>`).join('');
    $('empty').hidden = list.length > 0;
    $('more').hidden = list.length <= shown;
    $('more').textContent = `Show more (${fmtN(Math.min(shown, list.length))} of ${fmtN(list.length)} shown)`;
  }
  const fresh = () => { shown = STEP; renderEvents(); };
  function pickYear(y) {
    $('year').value = y;
    fresh();
    $('events-sec').scrollIntoView({ behavior: 'smooth' });
  }
  $('more').onclick = () => { shown += STEP; renderEvents(); };
  $('q').oninput = fresh;
  $('year').onchange = $('cap').onchange = fresh;
  $('showarb').onchange = () => $('events').classList.toggle('show-arb', $('showarb').checked);
  $('reset').onclick = () => { $('q').value = $('year').value = $('cap').value = ''; fresh(); };
  onSeg('fmt', () => { renderCharts(); fresh(); });

  // ---- Excel export: every tournament matching the filters, not just the rows shown ----
  $('dl').onclick = () => {
    const rows = filtered().map((e) => ({
      Start: e.start, End: e.end, Tournament: e.name, City: e.city, Format: e.fmt,
      'Rating limit': e.cap ? 'Below ' + e.cap : '', Players: e.n ?? '', Organizer: e.org,
      'Chief arbiter': e.arb, 'FIDE page': fide(e.id),
    }));
    const ws = XLSX.utils.json_to_sheet(rows);
    rows.forEach((_, i) => { const c = ws['J' + (i + 2)]; if (c) c.l = { Target: c.v }; }); // clickable FIDE link
    ws['!cols'] = [10, 10, 60, 24, 10, 12, 8, 30, 24, 50].map((wch) => ({ wch }));
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, 'Tournaments');
    XLSX.writeFile(wb, 'nepal_rated_tournaments.xlsx');
  };

  renderCharts();
  renderEvents();
}
